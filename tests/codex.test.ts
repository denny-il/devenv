import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { resolve } from "node:path";
import { afterEach, beforeEach, expect, test, vi } from "vitest";
import { setupCodex } from "../src/codex.ts";

let root: string;
const environment = () =>
  readFileSync(resolve(root, ".codex/environments/environment.toml"), "utf8");
const reset = "[ -x node_modules/.bin/devenv ] && node_modules/.bin/devenv reset || true";

beforeEach(() => {
  root = mkdtempSync(resolve(tmpdir(), "devenv-codex-"));
  vi.spyOn(console, "log").mockImplementation(() => {});
});
afterEach(() => {
  rmSync(root, { recursive: true, force: true });
  vi.restoreAllMocks();
  process.exitCode = undefined;
});

test("a project without an environment gets one that installs and cleans up", async () => {
  writeFileSync(resolve(root, "pnpm-lock.yaml"), "");
  await setupCodex(root, "shop");
  expect(environment()).toBe(
    `version = 1\nname = "shop"\n\n[setup]\nscript = "pnpm install"\n\n[cleanup]\nscript = '''\n# Removes this worktree's devenv stack before Codex deletes the worktree.\n${reset}\n'''\n`,
  );
});

test("an environment the app wrote keeps its setup and gains the cleanup, once", async () => {
  const written = `# THIS IS AUTOGENERATED. DO NOT EDIT MANUALLY\nversion = 1\nname = "Shop"\n\n[setup]\nscript = '''\npnpm install\n'''\n`;
  mkdirSync(resolve(root, ".codex/environments"), { recursive: true });
  writeFileSync(resolve(root, ".codex/environments/environment.toml"), written);

  await setupCodex(root, "shop");
  const once = environment();
  expect(once.startsWith(written)).toBe(true);
  expect(once.match(/^\[cleanup\]/gm)).toHaveLength(1);
  expect(once).toContain(reset);

  await setupCodex(root, "shop");
  expect(environment()).toBe(once);
});

test("a cleanup is recognised however the file spells it, and only if it resets", async () => {
  mkdirSync(resolve(root, ".codex/environments"), { recursive: true });
  for (const cleanup of [
    `  [ "cleanup" ]\nscript = "make clean"\n`,
    `cleanup = { script = "make clean" }\n`,
    `# TODO: add devenv reset\n[cleanup]\nscript = "make clean"\n`,
  ]) {
    const written = `version = 1\nname = "Shop"\n${cleanup}\n[setup]\nscript = ""\n`;
    writeFileSync(resolve(root, ".codex/environments/environment.toml"), written);
    process.exitCode = undefined;
    await setupCodex(root, "shop");
    expect(environment()).toBe(written);
    expect(process.exitCode).toBe(1);
  }
});

test("a cleanup script of the project's own is left alone and reported", async () => {
  const written = `version = 1\nname = "Shop"\n\n[setup]\nscript = ""\n\n[cleanup]\nscript = "make clean"\n`;
  mkdirSync(resolve(root, ".codex/environments"), { recursive: true });
  writeFileSync(resolve(root, ".codex/environments/environment.toml"), written);

  await setupCodex(root, "shop");
  expect(environment()).toBe(written);
  expect(process.exitCode).toBe(1);
});
